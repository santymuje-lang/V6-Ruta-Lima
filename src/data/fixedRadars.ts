export type FixedRadarType = 'urbano' | 'carretera';
export type FixedRadarPriority = 'alta' | 'normal';
export type FixedRadarPrecision = 'aproximado' | 'confirmado';

export interface FixedRadar {
  id: string;
  nombre: string;
  direccion: string;
  distrito: string;
  provincia: string;
  region: string;
  latitud: number | null;
  longitud: number | null;
  tipo: FixedRadarType;
  prioridad: FixedRadarPriority;
  precision: FixedRadarPrecision;
  // Metadatos opcionales de consulta y tramos Sutran
  nominatimQuery?: string;
  carretera?: string;
  kmInicio?: number;
  kmFin?: number;
  fuente?: string;
  bbox?: [number, number, number, number]; // [south, west, north, east]
  roadMatchRegex?: string;
  tramoCoordenadas?: [number, number][]; // [lat, lng]
  // Estado comunitario
  isCommunitySuggested?: boolean;
  confirmations?: number;
  confirmedBy?: string[];
  removedVotes?: number;
  removedBy?: string[];
}

